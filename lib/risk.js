function softmax(v) {
  const m = Math.max(...v)
  const e = v.map((x) => Math.exp(x - m))
  const s = e.reduce((a, x) => a + x, 0)
  return e.map((x) => x / s)
}

/**
 * pNN50 — доля пар соседних принятых интервалов, отличающихся больше чем на 50 мс, %.
 * @param {number[]} rr — все интервалы подряд
 * @param {boolean[]} kept — принят ли интервал
 */
export function pnn50(rr, kept) {
  let pairs = 0
  let over = 0
  for (let i = 1; i < rr.length; i++) {
    if (!kept[i] || !kept[i - 1]) continue
    pairs++
    if (Math.abs(rr[i] - rr[i - 1]) > 50) over++
  }
  return pairs ? (over / pairs) * 100 : NaN
}

// Тяжесть профиля вероятностей [норма, донозол., премор., срыв] (доли)
export function severity(four) {
  return four[1] + 2 * four[2] + 3 * four[3]
}

/**
 * Категория 1–10 по вероятностям четырёх состояний — с округлением в сторону риска.
 * @param {number[]} four — [норма, донозол., премор., срыв], доли
 */
export function riskCategory(four, cfg = RISK) {
  const s = severity(four)
  const k = cfg.PROFILES.findIndex((pr) => severity(pr.map((v) => v / 100)) >= s - 1e-9)
  return k < 0 ? 10 : k + 1
}

/**
 * Полная оценка адаптационного риска.
 * @param {{hr:number, si:number, pnn50:number, hfPct:number}} x
 */
export function adaptationRisk(x, cfg = RISK) {
  if (![x.hr, x.si, x.pnn50, x.hfPct].every(Number.isFinite)) return null
  const lin = (c) => c.c + c.hr * x.hr + c.si * x.si + c.pnn50 * x.pnn50 + c.hf * x.hfPct
  const fr = lin(cfg.FR)
  const sn = lin(cfg.SN)
  const stateProbs = softmax(cfg.STATES.map((s) => s.c + s.fr * fr + s.sn * sn))
  const p = Object.fromEntries(cfg.STATES.map((s, i) => [s.key, stateProbs[i]]))
  // Четыре группы рисунка 3.12: срыв адаптации = патологическое + тяжёлое патологическое
  const four = [p.norm, p.donoz, p.premorbid, p.path + p.severe]
  const category = riskCategory(four, cfg)
  const zone = cfg.ZONES.find((z) => category <= z.max)
  const top = cfg.STATES[stateProbs.indexOf(Math.max(...stateProbs))]
  return { fr, sn, states: p, four, category, zone, topState: top.label }
}
